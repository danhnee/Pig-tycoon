"""Generate Assets/Scripts/Controllers/Narrative/NarrativeMarks.g.cs from Assets/Art/PixelMyth/Maps/*_layout.json.
Marks: <map>:spawn, <map>:<landmark>, <map>:npc:<id> (home spot), <map>:station:<id>, <map>:zone:<id> (centre)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MAPS = {'village': 'Hub_Village', 'town': 'MarketTown', 'farm': 'Farm', 'forest': 'Forest_Primeval'}

def centre(o):
    for k in ('pos', 'position', 'tile', 'center', 'centre'):
        v = o.get(k)
        if isinstance(v, dict) and 'x' in v: return float(v['x']), float(v['y'])
        if isinstance(v, (list, tuple)) and len(v) >= 2: return float(v[0]), float(v[1])
    if 'x' in o and 'y' in o:
        x, y = float(o['x']), float(o['y'])
        if 'w' in o and 'h' in o: return x + float(o['w']) / 2, y + float(o['h']) / 2
        return x, y
    for k in ('rect', 'bounds'):
        r = o.get(k)
        if isinstance(r, dict) and 'x' in r: return float(r['x']) + float(r.get('w', 0)) / 2, float(r['y']) + float(r.get('h', 0)) / 2
        if isinstance(r, list) and len(r) == 4: return (r[0] + r[2]) / 2 if r[2] > r[0] else r[0] + r[2] / 2, (r[1] + r[3]) / 2 if r[3] > r[1] else r[1] + r[3] / 2
    return None

marks = {}
for short, loc in MAPS.items():
    d = json.load(open(os.path.join(ROOT, 'Assets/Art/PixelMyth/Maps', short + '_layout.json'), encoding='utf-8'))
    sp = d.get('spawn')
    if sp: marks[f'{short}:spawn'] = (float(sp['x']), float(sp['y']))
    lms = d.get('landmarks') or {}
    for i, v in (lms.items() if isinstance(lms, dict) else []):
        if isinstance(v, (list, tuple)) and len(v) >= 2: marks[f'{short}:{i}'] = (float(v[0]), float(v[1]))
    for n in d.get('npcs') or []:
        c = centre(n)
        if c and n.get('id'): marks[f'{short}:npc:{n["id"]}'] = c
    for z in d.get('zones') or []:
        r = z.get('rect'); zid = z.get('id') or z.get('name')
        if zid and isinstance(r, list) and len(r) == 4 and f'{short}:zone:{zid}' not in marks:
            marks[f'{short}:zone:{zid}'] = (r[0] + r[2] / 2, r[1] + r[3] / 2)
    for o in d.get('objects') or []:
        st = o.get('interact')
        if isinstance(st, dict) and st.get('id'):
            c = centre(o)
            if c: marks[f'{short}:station:{st["id"]}'] = c

lines = [f'            {{ "{k}", new Vector2({x:.2f}f, {y:.2f}f) }},' for k, (x, y) in sorted(marks.items())]
src = '''// <auto-generated> tools/narrative/gen_marks.py from Assets/Art/PixelMyth/Maps/*_layout.json. Re-run after map edits. </auto-generated>
using System.Collections.Generic;
using UnityEngine;

namespace PigTycoon.Presentation
{
    /// <summary>Story stage marks (ADR-0027): "village:gate", "village:npc:man", "farm:station:main_house"… in map tiles (= metres at 32 PPU).</summary>
    public static partial class NarrativeMarks
    {
        public static readonly Dictionary<string, Vector2> Table = new Dictionary<string, Vector2>(System.StringComparer.OrdinalIgnoreCase)
        {
''' + '\n'.join(lines) + '''
        };
    }
}
'''
out = os.path.join(ROOT, 'Assets/Scripts/Controllers/Narrative/NarrativeMarks.g.cs')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w', encoding='utf-8', newline='\n').write(src)
print(len(marks), 'marks ->', out)
